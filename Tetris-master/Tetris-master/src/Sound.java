/**
 * 효과음 종류. SoundManager.play()에 넘겨서 재생한다.
 * 소리는 파일이 아니라 SoundManager가 코드로 직접 만든다.
 */
public enum Sound
{
	/** 메뉴 버튼을 누를 때의 짧은 클릭음 */
	CLICK,

	/** 블록이나 캐릭터가 좌우로 움직이거나 한 칸 내려갈 때 */
	MOVE,

	/** 블록을 회전할 때 */
	ROTATE,

	/** 블록이 바닥에 고정될 때의 낮은 쿵 소리 */
	LOCK,

	/** 줄(3D에서는 층)을 지울 때의 상승음 */
	LINE_CLEAR,

	/** 아이템을 얻거나 쓸 때 */
	ITEM,

	/** 갤러그에서 총알을 쏠 때 */
	SHOOT,

	/** 갤러그에서 외계인을 맞혔을 때의 폭발음 */
	EXPLODE,

	/** 게임 오버나 패배했을 때의 하강음 */
	GAME_OVER,

	/** 클리어나 승리했을 때의 팡파르 */
	WIN
}
